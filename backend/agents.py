LABEL_MAP = {
    'obstructed visibility': 'visibility_obstruction',
    'pothole or damaged road surface': 'road_surface',
    'unsafe crossing': 'crossing_concern',
    'blocked pavement or cycle lane': 'access_obstruction',
    'speeding concern': 'speeding_concern',
    'broken traffic signal or lighting': 'signal_or_lighting',
    'other road concern': 'other_road_concern',
    'not a road report': 'out_of_scope',
}
CONTACT = re.compile(r'[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}|(?<!\w)(?:\+?\d[\d ()-]{7,}\d)(?!\w)')
INSTRUCTION = re.compile(r'(?i)\b(?:api[ _-]?key|ignore (?:all |your |previous )?instructions|system prompt|publish your|reveal your)\b')
CONCERN = re.compile(r'(?i)\b(?:see|visibility|sight|pothole|hole|damaged?|crack|surface|cross(?:ing)?|pavement|wheelchair|blocked?|obstruct\w*|speed\w*|fast|race|racing|lamp|light\w*|signal|drain|rattle\w*|danger\w*|unsafe|traffic|cars|van|bikes)\b')
DENIAL = re.compile(r"(?i)\b(?:there (?:is|are) no|no (?:pothole|problem|obstruction|damage|hazard)|(?:is|are|was) (?:not|n't) (?:blocked|broken|damaged|unsafe))\b")

@dataclass
class RoadLensDeps:
    repo: Repository
    turns: list[ResidentTurn] = field(default_factory=list)
    classifier: ClassifierSuggestion | None = None
    report: ReadyDraft | None = None
    question: str = ''
    locations: dict[str, ResolvedLocation] = field(default_factory=dict)
    metrics: dict[str, MetricResult] = field(default_factory=dict)
    records: dict[str, CollisionRecord] = field(default_factory=dict)
    nearby: dict[str, CollisionEvidence] = field(default_factory=dict)
    sources: dict[str, SourceNotes] = field(default_factory=dict)
    tools: list[ToolEvent] = field(default_factory=list)
    repairs: list[str] = field(default_factory=list)

    def event(self, name, inputs, output):
        if len(self.tools) < 20:
            self.tools.append(ToolEvent(name=name, inputs=inputs, output=output))


def _repair(deps: RoadLensDeps, message: str):
    # Messages contain only authored repair instructions, never rejected user/model text.
    if len(deps.repairs) < 10:
        deps.repairs.append(message)
    raise ModelRetry(message)


def resolve_location_impl(deps: RoadLensDeps, text: str) -> list[ResolvedLocation]:
    if len(text) > 4000:
        raise ModelRetry('Use a shorter exact resident location phrase.')
    if deps.turns and not any(normalize(text) in normalize(t.text) for t in deps.turns):
        raise ModelRetry('Resolve only an exact phrase present in an actual resident turn.')
    locations = deps.repo.resolve(text)
    deps.locations.update({p.place_id: p for p in locations})
    deps.event('resolve_location', {'input_sha256': digest(text), 'turn_ids': [t.turn_id for t in deps.turns if normalize(text) in normalize(t.text)]}, [p.model_dump(mode='json') for p in locations])
    return locations


def query_metrics_impl(deps: RoadLensDeps, query: EvidenceQuery) -> MetricResult:
    try:
        result = deps.repo.query(query)
    except (ValueError, KeyError) as exc:
        raise ModelRetry(str(exc)) from None
    deps.metrics[result.reference_id] = result
    deps.sources[result.source_id] = SOURCES[result.source_id]
    deps.event('query_metrics', query.model_dump(mode='json'), result.model_dump(mode='json'))
    return result


def find_local_collisions_impl(deps: RoadLensDeps, location: ResolvedLocation,
                               start: date, end: date, radius_metres: Literal[50, 100, 250] = 100) -> CollisionEvidence:
    supported = deps.locations.get(location.place_id) or (deps.report.location if deps.report and deps.report.location.place_id == location.place_id else None)
    if supported != location:
        raise ModelRetry('Resolve the location first and use its unmodified object.')
    try:
        result = deps.repo.nearby(location, start, end, radius_metres)
    except ValueError as exc:
        raise ModelRetry(str(exc)) from None
    deps.nearby[result.reference_id] = result
    deps.records.update({r.reference_id: r for r in result.records})
    deps.sources[LOCAL] = SOURCES[LOCAL]
    deps.event('find_local_collisions', {'place_id': location.place_id, 'start': str(start), 'end': str(end), 'radius_metres': radius_metres}, result.model_dump(mode='json'))
    return result


def get_source_notes_impl(deps: RoadLensDeps, source_id: SourceId) -> SourceNotes:
    result = SOURCES[source_id]
    deps.sources[source_id] = result
    deps.event('get_source_notes', {'source_id': source_id}, result.model_dump(mode='json'))
    return result


def get_collision_record_impl(deps: RoadLensDeps, collision_id: str) -> CollisionRecord | None:
    if not re.fullmatch(r'[A-Za-z0-9_-]{1,40}', collision_id):
        raise ModelRetry('Use a single supported local collision ID.')
    from contextlib import closing
    with closing(deps.repo.connect()) as db:
        row = db.execute('SELECT * FROM local_collisions WHERE local_ref=? LIMIT 1', [collision_id]).fetchone()
    record = deps.repo.local_record(row) if row else None
    if record:
        deps.records[record.reference_id] = record
        deps.sources[LOCAL] = SOURCES[LOCAL]
    deps.event('get_collision_record', {'collision_id': collision_id}, record.model_dump(mode='json') if record else {'found': False})
    return record


def readback_for(draft: ReadyDraft) -> str:
    labels = {
        Issue.visibility_obstruction: 'A visibility concern',
        Issue.road_surface: 'A road surface concern',
        Issue.crossing_concern: 'A crossing concern',
        Issue.access_obstruction: 'An access obstruction concern',
        Issue.speeding_concern: 'A speeding concern',
        Issue.signal_or_lighting: 'A signal or lighting concern',
        Issue.other_road_concern: 'A road concern',
    }
    location = draft.location.display_name.replace(' / ', ' and ')
    return f'{labels[draft.issue]} at {location}. Shall I submit that to RoadLens for review?'


def validate_intake_output(deps: RoadLensDeps, output: IntakeOutput) -> IntakeOutput:
    if not isinstance(output, ReadyDraft):
        if CONTACT.search(output.question if isinstance(output, NeedsClarification) else output.message):
            _repair(deps, 'Omit personal contact details from the response.')
        return output
    known = deps.locations.get(output.location.place_id)
    if known is None or known != output.location or deps.repo.location(output.location.place_id) != output.location:
        _repair(deps, 'Call resolve_location and use the exact returned location with provenance.')
    turns = {t.turn_id: t for t in deps.turns}
    for span in output.evidence_spans:
        if span.turn_id not in turns or span.quote not in turns[span.turn_id].text:
            _repair(deps, 'Each evidence quote must be an exact substring of its actual resident turn.')
    if not any(output.observation in t.text for t in deps.turns):
        _repair(deps, 'Observation must be an exact substring of one resident turn, not a paraphrase.')
    if not any(output.observation in span.quote or span.quote in output.observation for span in output.evidence_spans):
        _repair(deps, 'Include an evidence quote supporting the exact observation.')
    if CONTACT.search(output.observation) or any(CONTACT.search(s.quote) for s in output.evidence_spans):
        _repair(deps, 'Choose the concern sentence without personal contact details.')
    if INSTRUCTION.search(output.observation):
        _repair(deps, 'A location or instruction is not a road observation. Ask what concern the resident noticed.')
    if DENIAL.search(output.observation):
        _repair(deps, 'A denied problem is not a positive observation. Ask which concern should be reported.')
    # The most recent unambiguously stated junction supersedes earlier ones. Remove
    # explicit negative/correction clauses before resolution, without fuzzy matching.
    for turn in reversed(deps.turns):
        positive = re.split(r'(?i)[,;]\s*(?:not|rather than)\b', turn.text)[0]
        candidates = deps.repo.resolve(positive)
        if len(candidates) == 1:
            if candidates[0].place_id != output.location.place_id:
                _repair(deps, 'Use the latest positively stated junction, not an earlier corrected location.')
            break
    return output.model_copy(update={'readback': readback_for(output)})


def validate_evidence_output(deps: RoadLensDeps, output: EvidenceOutput) -> EvidenceOutput:
    if isinstance(output, NeedsClarification):
        if CONTACT.search(output.question):
            _repair(deps, 'Do not repeat contact information.')
        return output
    if any(ref not in deps.metrics for ref in output.metric_refs):
        _repair(deps, 'Metric references must come from query_metrics in this run.')
    if any(ref not in deps.records for ref in output.record_refs):
        _repair(deps, 'Record references must come from local collision tools in this run.')
    if len(set(output.metric_refs)) != len(output.metric_refs) or len(set(output.record_refs)) != len(output.record_refs):
        _repair(deps, 'Return each evidence reference once.')
    for ref in output.metric_refs:
        metric = deps.metrics[ref]
        expected = deps.repo.query(metric.query)
        if metric != expected or metric.source_id not in deps.sources:
            _repair(deps, 'Use the unmodified computed metric including its source, unit, period and geography.')
    used_sources = {deps.metrics[r].source_id for r in output.metric_refs} | {deps.records[r].source_id for r in output.record_refs}
    if len(used_sources) > 1 and 'overlapping_sources' not in output.limitations:
        _repair(deps, 'National and local sources overlap: include overlapping_sources and do not combine their totals.')
    required = set()
    if deps.report:
        if not isinstance(output, InspectionBrief):
            _repair(deps, 'For a confirmed report return an InspectionBrief.')
        if output.resident_concern != deps.report.observation:
            _repair(deps, 'Copy the confirmed observation exactly as resident_concern; do not add conclusions.')
        if not deps.nearby:
            _repair(deps, 'Retrieve nearby local collision evidence for the confirmed report location.')
        required.update(['no_causal_evidence', 'current_imagery_not_supplied', 'historic_conditions', 'unverified_resident_observation'])
    if isinstance(output, InspectionBrief) and not deps.report:
        _repair(deps, 'An InspectionBrief requires a confirmed report; answer the officer question with EvidenceAnswer.')
    question = deps.question.lower()
    if re.search(r'\b(cause|caused|causal|because|prove)\b', question):
        required.add('no_causal_evidence')
    if re.search(r'\b(safest|safer|risk|dangerous|danger)\b', question):
        required.add('no_exposure_denominator')
    if re.search(r'\b(current|today|photo|image|sightline)\b', question):
        required.add('current_imagery_not_supplied')
    if any(ref.startswith(LOCAL + ':') for ref in output.record_refs):
        required.add('historic_conditions')
    if not required.issubset(output.limitations):
        _repair(deps, 'Include applicable limitations: ' + ', '.join(sorted(required)) + '.')
    # No free numeric/causal prose exists in this output contract. Counts and descriptions
    # are rendered solely from the registry, while checks/limitations use fixed enums.
    return output


def create_intake_agent(model=None):
    agent = Agent(model, deps_type=RoadLensDeps, output_type=[ReadyDraft, NeedsClarification, OutOfScope],
                  instructions=INTAKE_PROMPT, name='IntakeAgent', retries=2, model_settings=AGENT_MODEL_SETTINGS)
    @agent.tool
    def resolve_location(ctx: RunContext[RoadLensDeps], text: str) -> list[ResolvedLocation]:
        """Resolve an actual resident phrase to supported, provenance-backed Cambridge junctions."""
        return resolve_location_impl(ctx.deps, text)
    @agent.output_validator
    def validate(ctx: RunContext[RoadLensDeps], output: ReadyDraft | NeedsClarification | OutOfScope):
        return validate_intake_output(ctx.deps, output)
    return agent


def create_evidence_agent(model=None):
    agent = Agent(model, deps_type=RoadLensDeps, output_type=[EvidenceAnswer, InspectionBrief, NeedsClarification],
                  instructions=EVIDENCE_PROMPT, name='EvidenceAgent', retries=2, model_settings=AGENT_MODEL_SETTINGS)
    @agent.tool
    def resolve_location(ctx: RunContext[RoadLensDeps], text: str) -> list[ResolvedLocation]:
        """Resolve a named Cambridge junction to a supported reference point."""
        return resolve_location_impl(ctx.deps, text)
    @agent.tool
    def query_metrics(ctx: RunContext[RoadLensDeps], query: EvidenceQuery) -> MetricResult:
        """Compute a bounded collision or casualty count; unknown ages are excluded from children."""
        return query_metrics_impl(ctx.deps, query)
    @agent.tool
    def find_local_collisions(ctx: RunContext[RoadLensDeps], location: ResolvedLocation, start: date,
                              end: date, radius_metres: Literal[50, 100, 250] = 100) -> CollisionEvidence:
        """Retrieve separate local, historical collision records within an EPSG:27700 radius."""
        return find_local_collisions_impl(ctx.deps, location, start, end, radius_metres)
    @agent.tool
    def get_source_notes(ctx: RunContext[RoadLensDeps], source_id: SourceId) -> SourceNotes:
        """Get provenance, source period and caveats for an official snapshot."""
        return get_source_notes_impl(ctx.deps, source_id)
    @agent.tool
    def get_collision_record(ctx: RunContext[RoadLensDeps], collision_id: str) -> CollisionRecord | None:
        """Look up one exact local record, preserving collision severity and casualty count as distinct fields."""
        return get_collision_record_impl(ctx.deps, collision_id)
    @agent.output_validator
    def validate(ctx: RunContext[RoadLensDeps], output: EvidenceAnswer | InspectionBrief | NeedsClarification):
        return validate_evidence_output(ctx.deps, output)
    return agent


def google_model(api_key=None):
    return GoogleModel(MODEL, provider=GoogleProvider(api_key=api_key or os.environ['GEMINI_API_KEY']))


def model_version(result) -> str:
    for message in reversed(result.all_messages()):
        if getattr(message, 'kind', '') == 'response':
            details = getattr(message, 'provider_details', None) or {}
            # Record an actual provider version only when returned; model_name is the
            # actual response model ID, rather than an invented snapshot suffix.
            return str(details.get('model_version') or details.get('modelVersion') or getattr(message, 'model_name', None) or 'not_supplied')
    return 'not_supplied'


def redacted_classifier(value: ClassifierSuggestion | None):
    if value is None: return None
    return value.model_copy(update={'entities': [e.model_copy(update={'text': CONTACT.sub('[contact redacted]', e.text)}) for e in value.entities]})


def run_summary(result, deps, prompt, elapsed) -> RunSummary:
    usage = result.usage
    usage_data = asdict(usage) if is_dataclass(usage) else (usage.model_dump() if hasattr(usage, 'model_dump') else {})
    return RunSummary(run_id='run:' + uuid4().hex, model=MODEL, model_version=model_version(result),
                      classifier=redacted_classifier(deps.classifier), tools=deps.tools,
                      validation_repairs=deps.repairs, usage=usage_data, elapsed_seconds=round(elapsed, 4),
                      outcome=result.output.kind, data_hashes=deps.repo.hashes,
                      prompt_hash=hashlib.sha256(prompt.encode()).hexdigest(),
                      code_commit=os.getenv('ROADLENS_CODE_COMMIT', 'working-tree-uncommitted'))


def intake_user_prompt(request, classifier):
    return json.dumps({'resident_turns': [t.model_dump(mode='json') for t in request.turns],
                       'classifier_advisory': classifier.model_dump(mode='json') if classifier else None,
                       'classifier_label_mapping': LABEL_MAP}, ensure_ascii=False)


def evidence_user_prompt(question, report):
    return json.dumps({'officer_question': question, 'confirmed_report': report.model_dump(mode='json') if report else None}, ensure_ascii=False)


async def prepare(request: PrepareRequest, classifier: Callable[[str], Awaitable[ClassifierSuggestion | dict]] | None = None,
                  *, repo=None, api_key=None, model=None) -> IntakeResponse:
    request = PrepareRequest.model_validate(request)
    started = time.perf_counter()
    deps = RoadLensDeps(repo=repo or Repository(), turns=request.turns)
    async with asyncio.timeout(90):
        if classifier is not None:
            text = '\n'.join(t.text for t in request.turns)
            suggestion = await classifier(text)
            deps.classifier = ClassifierSuggestion.model_validate(suggestion)
            deps.event('classify_resident_text', {'input_sha256': digest(text), 'characters': len(text)}, redacted_classifier(deps.classifier).model_dump(mode='json'))
        agent = create_intake_agent(model or google_model(api_key))
        result = await agent.run(intake_user_prompt(request, deps.classifier), deps=deps,
                                usage_limits=UsageLimits(request_limit=6, tool_calls_limit=8, output_tokens_limit=AGENT_OUTPUT_TOKEN_LIMIT))
    return IntakeResponse(output=result.output, run=run_summary(result, deps, INTAKE_PROMPT, time.perf_counter() - started))


def evidence_bundle(deps: RoadLensDeps, output: EvidenceOutput) -> EvidenceBundle:
    # Include only selected metrics, while nearby records support the dated map/list.
    metric_refs = getattr(output, 'metric_refs', [])
    record_refs = set(getattr(output, 'record_refs', []))
    for nearby in deps.nearby.values():
        record_refs.update(r.reference_id for r in nearby.records)
    return EvidenceBundle(metrics=[deps.metrics[r] for r in metric_refs],
                          records=[deps.records[r] for r in sorted(record_refs)],
                          nearby=list(deps.nearby.values()), sources=list(deps.sources.values()),
                          unknowns=getattr(output, 'limitations', []))


async def analyze(question: str, report: ReadyDraft | None = None, *, repo=None, api_key=None, model=None) -> AnalysisResult:
    if not 3 <= len(question) <= 2000: raise ValueError('Question must contain 3–2000 characters')
    if report is not None: report = ReadyDraft.model_validate(report)
    deps = RoadLensDeps(repo=repo or Repository(), report=report, question=question)
    if report: deps.locations[report.location.place_id] = report.location
    started = time.perf_counter()
    async with asyncio.timeout(90):
        result = await create_evidence_agent(model or google_model(api_key)).run(
            evidence_user_prompt(question, report), deps=deps,
            usage_limits=UsageLimits(request_limit=6, tool_calls_limit=8, output_tokens_limit=AGENT_OUTPUT_TOKEN_LIMIT))
    return AnalysisResult(output=result.output, evidence=evidence_bundle(deps, result.output),
                          run=run_summary(result, deps, EVIDENCE_PROMPT, time.perf_counter() - started))
